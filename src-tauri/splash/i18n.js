/** Testi della lingua `locale` (italiano se sconosciuta): t(chiave, parametri), t.n(chiave, n, parametri) per i plurali. */
globalThis.agentOfficeTexts = (locale) => {
  const all = globalThis.AGENT_OFFICE_I18N;
  const lang = Object.hasOwn(all, locale) ? locale : 'it';
  const rules = new Intl.PluralRules(lang);
  const t = (key, params) => String(all[lang][key] ?? all.it[key] ?? key)
    .replace(/\{(\w+)\}/g, (m, name) => (params && Object.hasOwn(params, name) ? String(params[name]) : m));
  t.n = (key, n, params) => t(`${key}.${rules.select(n) === 'one' ? 'one' : 'other'}`, { n, ...params });
  t.locale = lang;
  return t;
};
